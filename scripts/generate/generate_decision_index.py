#!/usr/bin/env python3
"""Generate docs/adr/README.md from the ADRs in docs/adr/.

The index exists so an agent can find which ADR owns a boundary before opening
one, and it is generated so it cannot fall behind the ADRs it indexes. An ADR
declares which canonical decisions it establishes through `decisions: [N]` in its
front matter; that link is what makes a decision number citable.

Pass --check to fail when the committed projection is stale.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = Path("docs/adr/README.md")
FRONT_MATTER = re.compile(r"\A---\n(.*?)\n---\n", re.DOTALL)
HEADER = """---
title: "Generated ADR index"
normative: false
audience: PROJECT_SCOPED
---

# ADR index

<!-- GENERATED by scripts/generate/generate_decision_index.py from docs/adr/*.md; do not edit. -->

An ADR states a decision and its rationale. The numbered rules it establishes live in
[canonical decisions](../00-canonical-decisions.md); this table maps one to the other.

Write one as `NNNN-short-title.md` with front matter declaring `title`, `status`
(proposed, accepted, superseded or rejected), `normative: true`, `audience`, and
`decisions: [N]` for every canonical decision it establishes. Keep the body to
Context, Decision and Consequences; an ADR that needs more room is usually two
decisions. Open one whenever a change alters architecture, a cross-module
contract, infrastructure, data layout, security posture or developer workflow.

| ADR | Title | Status | Canonical decisions |
|---|---|---|---|
"""


def render(root: Path) -> str:
    rows = []
    for path in sorted((root / "docs" / "adr").glob("[0-9][0-9][0-9][0-9]-*.md")):
        match = FRONT_MATTER.match(path.read_text(encoding="utf-8"))
        fields = yaml.safe_load(match.group(1)) if match else {}
        fields = fields if isinstance(fields, dict) else {}
        title = str(fields.get("title") or path.stem).replace("|", "\\|")
        status = str(fields.get("status") or "--").upper()
        decisions = fields.get("decisions") or []
        rows.append(
            f"| [{path.name[:4]}]({path.name}) | {title} | {status} "
            f"| {', '.join(str(d) for d in decisions) or '--'} |"
        )
    return HEADER + "\n".join(rows) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    rendered = render(args.root)
    target = args.root / OUTPUT
    if args.check:
        current = target.read_text(encoding="utf-8") if target.is_file() else ""
        if current != rendered:
            print(
                f"{OUTPUT} is stale. Regenerate with "
                "scripts/generate/generate_decision_index.py.",
                file=sys.stderr,
            )
            return 1
        print(f"OK: {OUTPUT} matches the ADRs.")
        return 0

    target.write_text(rendered, encoding="utf-8")
    print(f"Wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
