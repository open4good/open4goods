package org.open4goods.nudgerfrontapi.dto.category;

import io.swagger.v3.oas.annotations.media.Schema;

/**
 * A criterion as reasoned by the stored AI audit of the ImpactScore, with its justification.
 */
public record ImpactScoreAuditCriterionDto(
        @Schema(description = "Criterion key, as in the weights", example = "WARRANTY")
        String key,
        @Schema(description = "Weight proposed by the audit, between 0 and 1", example = "0.07", nullable = true)
        Double weight,
        @Schema(description = "Direction of the criterion: higher_is_better, lower_is_better or categorical", example = "higher_is_better", nullable = true)
        String directionality,
        @Schema(description = "Justification of the criterion and of its weight, generated by the audit", nullable = true)
        String rationale,
        @Schema(description = "Strength of the evidence behind the criterion (high, medium, low)", example = "high", nullable = true)
        String evidenceLevel
) {
}
