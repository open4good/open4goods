package org.open4goods.nudgerfrontapi.dto.auth;

import io.swagger.v3.oas.annotations.media.Schema;

/**
 * Google SSO login request payload.
 * <p>
 * The Nuxt BFF performs the Authorization Code with PKCE exchange and forwards
 * only the resulting Google ID token together with the nonce it generated for
 * that authorization request, so front-api can verify the ID token was minted
 * for this exact sign-in attempt.
 * </p>
 */
public record GoogleSsoLoginRequest(
        @Schema(description = "Google-issued OIDC ID token", example = "eyJhbGciOi...")
        String idToken,
        @Schema(description = "Nonce generated by the BFF for the authorization request", example = "n-0S6_WzA2Mj")
        String nonce
) {
}
