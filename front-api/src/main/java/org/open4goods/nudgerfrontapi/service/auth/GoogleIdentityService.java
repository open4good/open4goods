package org.open4goods.nudgerfrontapi.service.auth;

import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.util.List;

import org.open4goods.nudgerfrontapi.config.properties.GoogleSsoProperties;
import org.open4goods.nudgerfrontapi.service.exception.GoogleIdentityVerificationException;
import org.open4goods.nudgerfrontapi.service.exception.GoogleSsoDisabledException;
import org.open4goods.nudgerfrontapi.utils.EmailMaskUtils;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.security.oauth2.jwt.Jwt;
import org.springframework.security.oauth2.jwt.JwtException;
import org.springframework.security.oauth2.jwt.NimbusJwtDecoder;
import org.springframework.stereotype.Service;
import org.springframework.util.StringUtils;

import jakarta.annotation.PostConstruct;

/**
 * Verifies Google OIDC ID tokens forwarded by the Nuxt BFF and resolves the
 * caller's roles from the environment email allowlist.
 * <p>
 * Trust boundary: nothing from the raw ID token payload is used before the
 * signature, issuer, audience, expiry and nonce have all been checked. The
 * allowlist is deny-by-default - an unverified or unlisted email never
 * receives a role.
 * </p>
 * <p>
 * At startup, {@link #checkAllowlistConfiguration()} reports an allowlist
 * that cannot match any login (empty, or keys that lost their {@code @}).
 * </p>
 */
@Service
public class GoogleIdentityService {

    private static final Logger LOGGER = LoggerFactory.getLogger(GoogleIdentityService.class);

    private final GoogleSsoProperties properties;
    private volatile NimbusJwtDecoder decoder;
    private volatile String decoderJwksUri;

    public GoogleIdentityService(GoogleSsoProperties properties) {
        this.properties = properties;
    }

    /**
     * Report, without failing the startup, an enabled Google SSO whose allowlist
     * cannot match any login.
     * <p>
     * A key without {@code @} is logged at ERROR: it almost always comes from a
     * YAML map key written without brackets, whose {@code @} Spring Boot drops
     * on binding, so every login of that user is refused with a 401. Keys are
     * masked in the log. The application keeps starting so that the rest of
     * front-api stays available; the log is the operator's signal.
     * </p>
     */
    @PostConstruct
    public void checkAllowlistConfiguration() {
        if (!properties.isEnabled()) {
            return;
        }
        if (properties.getRoleAllowlist().isEmpty()) {
            LOGGER.warn("Google SSO is enabled but front.security.google-sso.role-allowlist is empty: "
                    + "every Google login will be refused.");
            return;
        }
        List<String> malformed = properties.malformedAllowlistKeys();
        if (!malformed.isEmpty()) {
            LOGGER.error("Google SSO role allowlist has {} key(s) that are not e-mail addresses ({}): "
                    + "these entries never match a login. Spring Boot drops the '@' of an unbracketed map key; "
                    + "write each key of front.security.google-sso.role-allowlist with brackets and quotes, "
                    + "e.g. \"[adresse@domaine]\": [ROLE_SITEEDITOR].",
                    malformed.size(),
                    malformed.stream().map(EmailMaskUtils::mask).sorted().toList());
        }
    }

    /**
     * Verify a Google ID token and resolve the caller's allowlisted roles.
     *
     * @param idToken       raw Google-issued ID token
     * @param expectedNonce nonce generated by the BFF for this authorization request
     * @return the resolved identity, never with an empty role list
     * @throws GoogleSsoDisabledException          when the feature flag is off
     * @throws GoogleIdentityVerificationException when the token is invalid, unverified,
     *                                              replayed with a mismatched nonce, or the
     *                                              email is absent from the allowlist
     */
    public GoogleIdentity verify(String idToken, String expectedNonce) {
        if (!properties.isEnabled()) {
            throw new GoogleSsoDisabledException();
        }
        if (!StringUtils.hasText(idToken)) {
            throw new GoogleIdentityVerificationException("Missing Google ID token");
        }
        if (!StringUtils.hasText(properties.getClientId())) {
            throw new GoogleIdentityVerificationException("Google SSO client id is not configured");
        }

        Jwt jwt;
        try {
            jwt = decoder().decode(idToken);
        } catch (JwtException | IllegalArgumentException ex) {
            throw new GoogleIdentityVerificationException("Google ID token verification failed", ex);
        }

        if (jwt.getIssuer() == null || !properties.getIssuer().equals(jwt.getIssuer().toString())) {
            throw new GoogleIdentityVerificationException("Google ID token issuer mismatch");
        }
        List<String> audience = jwt.getAudience();
        if (audience == null || !audience.contains(properties.getClientId())) {
            throw new GoogleIdentityVerificationException("Google ID token audience mismatch");
        }
        if (jwt.getExpiresAt() == null) {
            throw new GoogleIdentityVerificationException("Google ID token is missing an expiry");
        }
        if (!nonceMatches(expectedNonce, jwt.getClaimAsString("nonce"))) {
            throw new GoogleIdentityVerificationException("Google ID token nonce mismatch");
        }
        if (!Boolean.TRUE.equals(jwt.getClaim("email_verified"))) {
            throw new GoogleIdentityVerificationException("Google account email is not verified");
        }
        String email = jwt.getClaimAsString("email");
        if (!StringUtils.hasText(email)) {
            throw new GoogleIdentityVerificationException("Google ID token is missing an email");
        }

        List<String> roles = properties.rolesFor(email);
        if (roles.isEmpty()) {
            throw new GoogleIdentityVerificationException("Email " + EmailMaskUtils.mask(email)
                    + " is not present in the environment role allowlist ("
                    + properties.getRoleAllowlist().size() + " entries)");
        }
        return new GoogleIdentity(email, roles);
    }

    /**
     * Constant-time, Unicode-safe nonce comparison. Comparing raw
     * {@code String#equals} (or lengths) leaks timing information and can
     * desynchronize on multi-byte UTF-16 surrogate pairs; comparing UTF-8 byte
     * arrays with {@link MessageDigest#isEqual} avoids both.
     */
    private boolean nonceMatches(String expected, String actual) {
        if (expected == null || actual == null) {
            return false;
        }
        byte[] expectedBytes = expected.getBytes(StandardCharsets.UTF_8);
        byte[] actualBytes = actual.getBytes(StandardCharsets.UTF_8);
        return MessageDigest.isEqual(expectedBytes, actualBytes);
    }

    private NimbusJwtDecoder decoder() {
        String jwksUri = properties.getJwksUri();
        NimbusJwtDecoder current = decoder;
        if (current == null || !jwksUri.equals(decoderJwksUri)) {
            synchronized (this) {
                if (decoder == null || !jwksUri.equals(decoderJwksUri)) {
                    decoder = NimbusJwtDecoder.withJwkSetUri(jwksUri).build();
                    decoderJwksUri = jwksUri;
                }
            }
        }
        return decoder;
    }
}
