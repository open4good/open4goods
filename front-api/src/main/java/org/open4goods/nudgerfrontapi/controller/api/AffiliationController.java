package org.open4goods.nudgerfrontapi.controller.api;

import java.net.URI;
import java.nio.charset.StandardCharsets;
import java.util.Locale;

import org.open4goods.model.RolesConstants;
import org.open4goods.model.localization.DomainLanguage;
import org.open4goods.nudgerfrontapi.service.AffiliationService;
import org.open4goods.nudgerfrontapi.service.exception.InvalidAffiliationTokenException;
import org.springframework.http.CacheControl;
import org.springframework.http.HttpHeaders;
import org.springframework.http.HttpStatus;
import org.springframework.http.ProblemDetail;
import org.springframework.http.ResponseEntity;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.validation.annotation.Validated;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestHeader;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.enums.ParameterIn;
import io.swagger.v3.oas.annotations.headers.Header;
import io.swagger.v3.oas.annotations.media.Content;
import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.tags.Tag;

/**
 * REST controller responsible for resolving affiliation redirect tokens and registering the redirect.
 */
@RestController
@RequestMapping("/affiliations")
@Validated
@PreAuthorize("hasAnyAuthority('" + RolesConstants.ROLE_FRONTEND + "', '" + RolesConstants.ROLE_EDITOR + "')")
@Tag(name = "Affiliation", description = "Resolve affiliation redirect tokens and record outbound clicks (no personal data).")
public class AffiliationController {

    /** Optional header carrying the path of the page the click comes from. */
    public static final String ORIGIN_HEADER = "X-Affiliation-Origin";

    private final AffiliationService affiliationService;

    public AffiliationController(AffiliationService affiliationService) {
        this.affiliationService = affiliationService;
    }

    /**
     * Resolve an affiliation token using an idempotent GET request.
     *
     * @param token          encrypted affiliation token generated by the product catalogue
     * @param domainLanguage domain language hint required by the API contract
     * @param originPath     {@code X-Affiliation-Origin} header (optional, ignored unless a bare path)
     * @return a non-cacheable 302 redirect towards the decoded affiliation URL
     */
    @GetMapping("/redirect")
    @Operation(
            summary = "Resolve affiliation token (GET)",
            description = "Decode an affiliation token, record the click (network, merchant, product GTIN, originating "
                    + "path and target host; no IP, no user agent) and redirect the client with a non-cacheable 302.",
            parameters = {
                    @Parameter(name = "token", in = ParameterIn.QUERY, required = true,
                            description = "Affiliation token obtained from the product catalogue.",
                            schema = @Schema(type = "string")),
                    @Parameter(name = "domainLanguage", in = ParameterIn.QUERY, required = true,
                            description = "Language driving localisation of textual fields (future use).",
                            schema = @Schema(implementation = DomainLanguage.class)),
                    @Parameter(name = AffiliationController.ORIGIN_HEADER, in = ParameterIn.HEADER, required = false,
                            description = "Path of the page the click comes from (path only: starts with '/', "
                                    + "no query nor fragment, at most 200 characters). Any other value is ignored.",
                            schema = @Schema(type = "string", maxLength = 200, example = "/fours/four-encastrable"))
            },
            responses = {
                    @ApiResponse(responseCode = "302", description = "Redirect to affiliation partner (Cache-Control: no-store)",
                            headers = {
                                    @Header(name = HttpHeaders.LOCATION,
                                            description = "Decoded affiliation destination.",
                                            schema = @Schema(type = "string", format = "uri")),
                                    @Header(name = "X-Locale",
                                            description = "Resolved locale for textual payloads.",
                                            schema = @Schema(type = "string", example = "fr-FR"))
                            }),
                    @ApiResponse(responseCode = "400", description = "Invalid affiliation token",
                            content = @Content(mediaType = "application/problem+json",
                                    schema = @Schema(implementation = ProblemDetail.class))),
                    @ApiResponse(responseCode = "500", description = "Internal server error",
                            content = @Content(mediaType = "application/problem+json",
                                    schema = @Schema(implementation = ProblemDetail.class)))
            }
    )
    public ResponseEntity<Void> redirectGet(@RequestParam String token,
            @RequestParam(name = "domainLanguage") DomainLanguage domainLanguage,
            @RequestHeader(name = ORIGIN_HEADER, required = false) String originPath) {
        return handleRedirect(token, domainLanguage, originPath);
    }

    /**
     * Resolve an affiliation token using a POST request (mirrors the GET contract).
     *
     * @param token          encrypted affiliation token generated by the product catalogue
     * @param domainLanguage domain language hint required by the API contract
     * @param originPath     {@code X-Affiliation-Origin} header (optional, ignored unless a bare path)
     * @return a non-cacheable 302 redirect towards the decoded affiliation URL
     */
    @PostMapping("/redirect")
    @Operation(
            summary = "Resolve affiliation token (POST)",
            description = "Decode an affiliation token, record the click (network, merchant, product GTIN, originating "
                    + "path and target host; no IP, no user agent) and redirect the client with a non-cacheable 302.",
            parameters = {
                    @Parameter(name = "token", in = ParameterIn.QUERY, required = true,
                            description = "Affiliation token obtained from the product catalogue.",
                            schema = @Schema(type = "string")),
                    @Parameter(name = "domainLanguage", in = ParameterIn.QUERY, required = true,
                            description = "Language driving localisation of textual fields (future use).",
                            schema = @Schema(implementation = DomainLanguage.class)),
                    @Parameter(name = AffiliationController.ORIGIN_HEADER, in = ParameterIn.HEADER, required = false,
                            description = "Path of the page the click comes from (path only: starts with '/', "
                                    + "no query nor fragment, at most 200 characters). Any other value is ignored.",
                            schema = @Schema(type = "string", maxLength = 200, example = "/fours/four-encastrable"))
            },
            responses = {
                    @ApiResponse(responseCode = "302", description = "Redirect to affiliation partner (Cache-Control: no-store)",
                            headers = {
                                    @Header(name = HttpHeaders.LOCATION,
                                            description = "Decoded affiliation destination.",
                                            schema = @Schema(type = "string", format = "uri")),
                                    @Header(name = "X-Locale",
                                            description = "Resolved locale for textual payloads.",
                                            schema = @Schema(type = "string", example = "fr-FR"))
                            }),
                    @ApiResponse(responseCode = "400", description = "Invalid affiliation token",
                            content = @Content(mediaType = "application/problem+json",
                                    schema = @Schema(implementation = ProblemDetail.class))),
                    @ApiResponse(responseCode = "500", description = "Internal server error",
                            content = @Content(mediaType = "application/problem+json",
                                    schema = @Schema(implementation = ProblemDetail.class)))
            }
    )
    public ResponseEntity<Void> redirectPost(@RequestParam String token,
            @RequestParam(name = "domainLanguage") DomainLanguage domainLanguage,
            @RequestHeader(name = ORIGIN_HEADER, required = false) String originPath) {
        return handleRedirect(token, domainLanguage, originPath);
    }

    private ResponseEntity<Void> handleRedirect(String token, DomainLanguage domainLanguage, String originPath) {
        String url = affiliationService.trackRedirect(token, originPath);
        try {
            URI target = toRedirectUri(url);
            // 302 + no-store: a 301 may be cached by the browser, and a cached click never reaches the server.
            return ResponseEntity.status(HttpStatus.FOUND)
                    .cacheControl(CacheControl.noStore())
                    .header(HttpHeaders.LOCATION, target.toString())
                    .header("X-Locale", domainLanguage.languageTag())
                    .build();
        }
        catch (IllegalArgumentException exception) {
            throw new InvalidAffiliationTokenException("Decoded URL is not a valid URI.", exception);
        }
    }

    /**
     * Build the redirect target from a merchant URL. Merchant feeds (e.g. Carrefour marketplace) may carry
     * characters that {@link URI} rejects (spaces, {@code |}, braces, brackets, quotes, raw non-ASCII, a lone
     * {@code %}, a second {@code #}). Those are percent-encoded; existing {@code %XX} escapes and URI delimiters
     * are preserved. Only absolute http/https targets are accepted, to prevent open redirects to other schemes.
     *
     * @param url raw merchant URL
     * @return a valid absolute http(s) URI
     * @throws IllegalArgumentException when the URL cannot be turned into a valid http(s) URI
     */
    static URI toRedirectUri(String url) {
        if (url == null || url.isBlank()) {
            throw new IllegalArgumentException("Empty URL");
        }
        byte[] bytes = url.trim().getBytes(StandardCharsets.UTF_8);
        StringBuilder sb = new StringBuilder();
        boolean fragmentStarted = false;
        for (int i = 0; i < bytes.length; i++) {
            int c = bytes[i] & 0xFF;
            boolean legal = c > 0x20 && c < 0x7F && "\"<>\\^`{|}[]".indexOf(c) < 0;
            if (c == '%' && !(i + 2 < bytes.length && isHex(bytes[i + 1]) && isHex(bytes[i + 2]))) {
                legal = false;
            }
            else if (c == '#') {
                legal = !fragmentStarted;
                fragmentStarted = true;
            }
            if (legal) {
                sb.append((char) c);
            }
            else {
                sb.append('%').append(String.format(Locale.ROOT, "%02X", c));
            }
        }
        URI uri = URI.create(sb.toString());
        String scheme = uri.getScheme();
        if (scheme == null || !(scheme.equalsIgnoreCase("http") || scheme.equalsIgnoreCase("https"))
                || uri.getHost() == null) {
            throw new IllegalArgumentException("Unsupported redirect target");
        }
        return uri;
    }

    private static boolean isHex(byte b) {
        return (b >= '0' && b <= '9') || (b >= 'a' && b <= 'f') || (b >= 'A' && b <= 'F');
    }
}
